using System;
using ClosedXML.Excel;

namespace InFine.QuantFinance.ExcelSamples;

/// <summary>04-Portfolio-Risk: covariance estimators side by side, VaR and ES by three methods, VaR decomposition.</summary>
internal static class PortfolioRiskWorkbook
{
    public static readonly double[] Exposures = { 4_000_000, 3_000_000, 1_500_000, 6_000_000, -2_000_000 };
    public const int Days = SyntheticMarket.Days;
    public const int LastReturnRow = Days + 1;

    public static SampleBook Build(string fileName)
    {
        var book = new SampleBook(fileName);
        SampleWorkbooks.About(book, "Portfolio risk: covariance, VaR, ES and VaR decomposition",
            "A five-asset book over 250 days of daily returns: three covariance estimators side by side (QF.COV), 99% Value-at-Risk and " +
            "Expected Shortfall by historical, parametric and Cornish-Fisher methods (QF.VAR, QF.ES), and the allocation of the risk to the assets (QF.VAR.DECOMP).",
            new[]
            {
                "Returns: the date, the daily log returns of five assets, and the portfolio P&L of the current positions (one formula per day).",
                "Portfolio: confidence level and horizon, the positions, the VaR/ES table, P&L statistics, and the parametric and historical decompositions.",
                "Covariance: annualised sample, EWMA and Ledoit-Wolf (constant correlation) matrices, with a comparison of volatilities and of one correlation.",
            },
            new[]
            {
                "The returns are synthetic: a fixed-seed multivariate Student-t (5 degrees of freedom) with realistic volatilities and correlations and two stress episodes, " +
                    "so that the three VaR methods differ. They are generated by tools/InFine.QuantFinance.ExcelSamples and are the same on every run.",
                "Functions used: QF.COV, QF.VAR, QF.ES, QF.VAR.DECOMP. QF.VAR, QF.ES and QF.VAR.DECOMP take the returns range and one exposure per asset; with a ranges of this size they run inline.",
            });

        // ---------------------------------------------------------------- Returns
        var r = book.AddSheet("Returns");
        r.Widths((2, 14), (3, 11), (4, 11), (5, 11), (6, 11), (7, 11), (8, 16));
        // Column A is the margin on every sheet; this sheet starts at B so that the references stay uniform.
        r.Header("B1", "Date", "ESTOXX50", "SPX", "GOLD", "BUND", "EURUSD", "Portfolio P&L");
        var returns = SyntheticMarket.DailyLogReturns(Days);
        var dates = SyntheticMarket.Dates(Days);
        for (int i = 0; i < Days; i++)
        {
            int row = i + 2;
            r.Ws.Cell(row, 2).Value = dates[i];
            r.Ws.Cell(row, 2).Style.NumberFormat.Format = "dd-mmm-yyyy";
            for (int j = 0; j < SyntheticMarket.Assets.Length; j++)
            {
                var cell = r.Ws.Cell(row, 3 + j);
                r.StyleInput(cell, "0.00%");
                cell.Value = returns[i, j];
            }
            r.Calc($"H{row}", $"MMULT(C{row}:G{row},Exposures)", "#,##0");
        }
        r.Ws.SheetView.FreezeRows(1);
        r.Name("ReturnsData", $"C2:G{LastReturnRow}");
        r.Name("ReturnsHeader", $"C1:G{LastReturnRow}");
        r.Name("PnL", $"H2:H{LastReturnRow}");
        r.Note("J2", "Daily log returns (synthetic). Yellow because they are data you can paste your own over; keep one column per asset, oldest date first.");

        // ---------------------------------------------------------------- Portfolio
        var p = book.AddSheet("Portfolio");
        p.Widths((2, 34), (3, 16), (4, 16), (5, 14), (6, 14), (7, 16), (8, 14));
        p.Title("B1", "Value-at-Risk, Expected Shortfall and decomposition", "B2", "Yellow cells are inputs. VaR and ES are positive losses in currency units.");
        p.Header("B3", "Settings", "Value");
        p.Text("B4", "Confidence level");
        p.Input("C4", 0.99, "0.0%", "Alpha");
        p.Text("B5", "Horizon (days)");
        p.Input("C5", 1, "0", "Horizon");
        p.Text("B6", "EWMA decay lambda");
        p.Input("C6", 0.94, "0.00", "Lambda");
        p.Text("B7", "Periods per year");
        p.Input("C7", 252, "0", "PeriodsPerYear");

        p.Header("B9", "Position", "Exposure (EUR)");
        string[] names = SyntheticMarket.Assets;
        string[] columns = { "C", "D", "E", "F", "G" };
        for (int i = 0; i < names.Length; i++)
        {
            p.Calc($"B{10 + i}", $"Returns!{columns[i]}1");
            p.Input($"C{10 + i}", Exposures[i], "#,##0");
        }
        p.Name("Exposures", "C10:C14");
        p.Text("B15", "Gross exposure");
        p.Calc("C15", "SUMPRODUCT(ABS(C10:C14))", "#,##0");
        p.Text("B16", "Net exposure");
        p.Calc("C16", "SUM(C10:C14)", "#,##0");

        p.Header("B18", "Method", "VaR", "ES", "VaR / gross", "ES / VaR");
        string[] methods = { "HISTORICAL", "PARAMETRIC", "CORNISHFISHER" };
        for (int i = 0; i < methods.Length; i++)
        {
            int row = 19 + i;
            p.Input($"B{row}", methods[i]);
            p.Calc($"C{row}", $"QF.VAR(ReturnsData,Alpha,B{row},Horizon,Exposures)", "#,##0");
            p.Calc($"D{row}", $"QF.ES(ReturnsData,Alpha,B{row},Horizon,Exposures)", "#,##0");
            p.Calc($"E{row}", $"C{row}/$C$15", "0.00%");
            p.Calc($"F{row}", $"D{row}/C{row}", "0.00");
        }
        p.Note("B22", "Horizon scaling is the square-root-of-time rule for every method. CORNISHFISHER corrects the normal quantile for the skewness and kurtosis of the P&L.");

        p.Header("B24", "Portfolio P&L (1 day)", "Value");
        p.Text("B25", "Standard deviation");
        p.Calc("C25", "STDEV(PnL)", "#,##0");
        p.Text("B26", "Skewness");
        p.Calc("C26", "SKEW(PnL)", "0.00");
        p.Text("B27", "Excess kurtosis");
        p.Calc("C27", "KURT(PnL)", "0.00");
        p.Text("B28", "Historical VaR from the P&L column");
        p.Calc("C28", "QF.VAR(PnL,Alpha,\"HISTORICAL\",Horizon)", "#,##0");
        p.Text("B29", "Difference with the table above");
        p.Calc("C29", "C28-C19", "0.0E+00");
        p.Note("D28", "QF.VAR on a P&L sample (no positions argument)");

        p.Header("B31", "Parametric decomposition (delta-normal, exact)");
        p.Header("C31", "", "", "", "", "", "");
        p.Block("B32:H38", "QF.VAR.DECOMP(ReturnsHeader,Exposures,Alpha,\"PARAMETRIC\",Horizon,TRUE)");
        FormatDecomposition(p, 32);
        p.Text("B39", "Components add up to the total");
        p.Calc("C39", "IF(ABS(SUM(D33:D37)-D38)<=0.000001*D38,\"OK\",\"CHECK\")").Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Right;

        p.Header("B41", "Historical decomposition (kernel estimate: noisy on 250 days)");
        p.Header("C41", "", "", "", "", "", "");
        p.Block("B42:H48", "QF.VAR.DECOMP(ReturnsHeader,Exposures,Alpha,\"HISTORICAL\",Horizon,TRUE)");
        FormatDecomposition(p, 42);
        p.Text("B49", "Components add up to the total");
        p.Calc("C49", "IF(ABS(SUM(D43:D47)-D48)<=0.000001*D48,\"OK\",\"CHECK\")").Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Right;
        p.Note("B51", "Marginal VaR/ES are per unit of exposure; component = marginal x exposure; the components sum to the Total row. A negative component is a hedge.");

        // ---------------------------------------------------------------- Covariance
        var c = book.AddSheet("Covariance");
        c.Widths((2, 22), (3, 12), (4, 12), (5, 12), (6, 12), (7, 12), (8, 4), (9, 26), (10, 12), (11, 12), (12, 12));
        c.Title("B1", "Covariance estimators", "B2", "Annualised covariance of the daily returns (x PeriodsPerYear). Settings Lambda and PeriodsPerYear are on the Portfolio sheet.");
        CovarianceBlock(c, 4, "SAMPLE (unbiased, equal weights)", "QF.COV(ReturnsData,\"SAMPLE\",,PeriodsPerYear)");
        CovarianceBlock(c, 14, "EWMA (RiskMetrics, decay Lambda)", "QF.COV(ReturnsData,\"EWMA\",Lambda,PeriodsPerYear)");
        CovarianceBlock(c, 24, "LW_CC (Ledoit-Wolf shrinkage to constant correlation)", "QF.COV(ReturnsData,\"LW_CC\",,PeriodsPerYear)");

        c.Header("I4", "Annualised volatility", "SAMPLE", "EWMA", "LW_CC");
        for (int i = 0; i < names.Length; i++)
        {
            int row = 5 + i;
            c.Calc($"I{row}", $"B{6 + i}");
            // Volatility of asset i is the square root of its diagonal element; the vol rows are 11, 21 and 31.
            c.Calc($"J{row}", $"{columns[i]}11", "0.0%");
            c.Calc($"K{row}", $"{columns[i]}21", "0.0%");
            c.Calc($"L{row}", $"{columns[i]}31", "0.0%");
        }
        c.Text("I10", "Correlation ESTOXX50 / SPX");
        c.Calc("J10", "D6/SQRT(C6*D7)", "0.00");
        c.Calc("K10", "D16/SQRT(C16*D17)", "0.00");
        c.Calc("L10", "D26/SQRT(C26*D27)", "0.00");
        c.Note("I12", "EWMA weights recent days more; Ledoit-Wolf shrinks the correlations towards their average.");

        return book;
    }

    private static void CovarianceBlock(Sx c, int top, string title, string formula)
    {
        string[] columns = { "C", "D", "E", "F", "G" };
        c.Header($"B{top}", title);
        c.Header($"C{top}", "", "", "", "", "");
        // Header row of asset names, then the matrix, then the annualised volatilities.
        c.Header($"B{top + 1}", "");
        for (int i = 0; i < 5; i++)
        {
            var h = c.Ws.Cell($"{columns[i]}{top + 1}");
            h.FormulaA1 = $"Returns!{columns[i]}1";
            h.Style.Font.Bold = true;
            h.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
            h.Style.Fill.BackgroundColor = Sx.OutputFill;
            var label = c.Ws.Cell($"B{top + 2 + i}");
            label.FormulaA1 = $"Returns!{columns[i]}1";
            label.Style.Font.Bold = true;
        }
        c.Block($"C{top + 2}:G{top + 6}", formula, "0.000000");
        c.Text($"B{top + 7}", "Volatility");
        for (int i = 0; i < 5; i++)
            c.Calc($"{columns[i]}{top + 7}", $"SQRT({columns[i]}{top + 2 + i})", "0.0%");
    }

    private static void FormatDecomposition(Sx p, int top)
    {
        // Header row, five assets, total.
        var header = p.Ws.Range($"B{top}:H{top}");
        header.Style.Font.Bold = true;
        header.Style.Fill.BackgroundColor = Sx.OutputFill;
        header.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
        header.Style.NumberFormat.Format = "General";
        var total = p.Ws.Range($"B{top + 6}:H{top + 6}");
        total.Style.Font.Bold = true;
        int first = top + 1, last = top + 6;
        p.Ws.Range($"C{first}:C{last}").Style.NumberFormat.Format = "0.0000";
        p.Ws.Range($"D{first}:D{last}").Style.NumberFormat.Format = "#,##0";
        p.Ws.Range($"E{first}:E{last}").Style.NumberFormat.Format = "0.0%";
        p.Ws.Range($"F{first}:F{last}").Style.NumberFormat.Format = "0.0000";
        p.Ws.Range($"G{first}:G{last}").Style.NumberFormat.Format = "#,##0";
        p.Ws.Range($"H{first}:H{last}").Style.NumberFormat.Format = "0.0%";
    }
}
